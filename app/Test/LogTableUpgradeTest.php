<?php

use PHPUnit\Framework\TestCase;

require_once __DIR__ . '/MigrationLedgerStubs.php';
require_once APPLIBS . 'Migration/BaselineGenerator.php';
require_once APPLIBS . 'Migration/TableConverger.php';
require_once APPLIBS . 'Migration/LogTableUpgrade.php';

class LogTableUpgradeTest extends TestCase
{
    const MARIADB = '10.11.14-MariaDB-0ubuntu0.24.04.1';

    const MYSQL = '8.4.6';

    public function testLogsGetsUtf8mb4BinaryColumnsAndTheLogViewIndexes()
    {
        $sql = $this->render('logs', 'logs_new', self::MARIADB);
        $this->assertStringContainsString('`id` bigint(20) NOT NULL AUTO_INCREMENT', $sql);
        $this->assertStringContainsString('`title` text CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL', $sql);
        $this->assertStringContainsString('`user_id` bigint(20) NOT NULL', $sql);
        foreach (array(
            '`idx_logs_action` (`action`)',
            '`idx_logs_created` (`created`)',
            '`idx_logs_email` (`email`)',
            '`idx_logs_model_id` (`model`, `model_id`)',
            '`idx_logs_org` (`org`)',
            '`idx_logs_user_id_action` (`user_id`, `action`)',
        ) as $index) {
            $this->assertStringContainsString('ADD INDEX ' . $index, $sql);
        }
    }

    public function testAuditLogsGetsTheCaseInsensitiveCollationOfEachServer()
    {
        $this->assertStringContainsString('COLLATE=utf8mb4_uca1400_ai_ci', $this->render('audit_logs', 'audit_logs_new', self::MARIADB));
        $sql = $this->render('audit_logs', 'audit_logs_new', self::MYSQL);
        $this->assertStringContainsString('COLLATE=utf8mb4_unicode_520_ci', $sql);
        $this->assertStringContainsString('ADD INDEX `model_id` (`model`, `model_id`)', $sql);
        $this->assertStringContainsString('ADD INDEX `authkey_id` (`authkey_id`)', $sql);
        $this->assertStringContainsString('ADD INDEX `action` (`action`)', $sql);
        $this->assertStringContainsString('`change` blob DEFAULT NULL', $sql);
    }

    public function testPostgresqlIndexNamesAreTheOnesAFreshInstallHas()
    {
        $sql = $this->render('audit_logs', 'audit_logs', null);
        $this->assertStringContainsString('"id" bigint GENERATED BY DEFAULT AS IDENTITY', $sql);
        $this->assertStringContainsString('CREATE INDEX "idx_audit_logs_event_id" ON "audit_logs" ("event_id");', $sql);
        $this->assertStringContainsString('CREATE INDEX "idx_audit_logs_model_id" ON "audit_logs" ("model", "model_id");', $sql);
        $this->assertStringContainsString('CREATE INDEX "idx_logs_org" ON "logs" ("org");', $this->render('logs', 'logs', null));
    }

    public function testNoIndexHasAPrefix()
    {
        foreach (LogTableUpgrade::TARGETS as $target) {
            foreach ($target['indexes'] as $index) {
                $this->assertArrayNotHasKey('length', $index);
            }
        }
    }

    public function testAnUnknownTableIsRefused()
    {
        $this->expectException(InvalidArgumentException::class);
        LogTableUpgrade::assertTable('access_logs');
    }

    /**
     * @param string $table
     * @param string $as
     * @param string|null $mysqlVersion null for PostgreSQL
     * @return string
     */
    private function render($table, $as, $mysqlVersion)
    {
        $grammar = $mysqlVersion === null
            ? AbstractGrammar::forDataSource(new MigrationTestPostgres())
            : AbstractGrammar::forDataSource(new MigrationTestMysqlExtended($mysqlVersion));
        $schema = new SchemaBuilder($grammar);
        TableConverger::emit($schema, TableConverger::creationPlan($as, LogTableUpgrade::TARGETS[$table]));
        return implode("\n", $schema->toSql());
    }
}
